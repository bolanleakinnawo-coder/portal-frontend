import { Link } from '../../lib/router';
import { useAuth } from '../../context/AuthContext';
import { useLoad } from '../../components/ui';
import { CapIcon, PrintIcon } from '../../components/Icons';
import { dateTime, getRegistration } from '../../api/services';
import { isStaff } from '../../config/roles';

/** Printable course registration slip (students see their own; staff can open any). */
export default function Slip({ id }) {
  const { user } = useAuth();
  const { data: reg, error } = useLoad(() => getRegistration(id), [id]);

  if (error) return <div className="center-screen"><p>{error}</p><Link to="/" className="btn btn-primary">Go home</Link></div>;
  if (!reg) return <div className="center-screen"><div className="spinner" /></div>;
  if (!isStaff(user) && reg.user !== user.id) return <div className="center-screen"><p>You can only view your own slip.</p></div>;

  const u = reg.student;
  return (
    <div className="slip-page">
      <div className="slip-actions no-print">
        <Link to={isStaff(user) ? '/admin/registrations' : '/dashboard/courses'} className="btn btn-outline">← Back</Link>
        <button className="btn btn-primary" onClick={() => window.print()}><PrintIcon width={18} height={18} /> Print slip</button>
      </div>
      <article className="slip">
        <header className="slip-head">
          <span className="logo-mark"><CapIcon /></span>
          <div>
            <h1>Bitly University</h1>
            <p>Postgraduate School · Course Registration Slip</p>
          </div>
        </header>
        <div className="slip-grid">
          <div><span>Name</span><strong>{reg.student_name}</strong></div>
          <div><span>Matric number</span><strong>{reg.matric_number}</strong></div>
          <div><span>Programme</span><strong>{reg.programme_label}</strong></div>
          <div><span>Department</span><strong>{reg.department_name}</strong></div>
          <div><span>Session</span><strong>{reg.session}</strong></div>
          <div><span>Semester / Level</span><strong className="cap">{reg.semester} · {reg.level}</strong></div>
          <div><span>Registration number</span><strong>{reg.number}</strong></div>
          <div><span>Date registered</span><strong>{dateTime(reg.created_at)}</strong></div>
        </div>
        <table className="slip-table">
          <thead><tr><th>#</th><th>Code</th><th>Course title</th><th className="right">Units</th></tr></thead>
          <tbody>
            {reg.course_list.map((c, i) => <tr key={c.id}><td>{i + 1}</td><td>{c.code}</td><td>{c.title}</td><td className="right">{c.units}</td></tr>)}
            <tr className="total"><td colSpan={3}>Total units</td><td className="right">{reg.total_units}</td></tr>
          </tbody>
        </table>
        <div className="slip-sign">
          <div><span /><p>Student’s signature</p></div>
          <div><span /><p>Head of Department</p></div>
          <div><span /><p>PG School Officer</p></div>
        </div>
        <p className="slip-foot">Generated by the Bitly University PG Portal for {u?.email}. Verify at the PG School office.</p>
      </article>
    </div>
  );
}
